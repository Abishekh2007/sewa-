// Shared UI primitives. Keep pages consistent: use these instead of ad-hoc styling.
import { useEffect, useRef, type ButtonHTMLAttributes, type ReactNode } from 'react';
import type { Confidence, Priority, SegmentStatus } from '../types';
import { STATUS_LABEL } from '../engine/evidence';

export const cx = (...c: (string | false | null | undefined)[]) => c.filter(Boolean).join(' ');

export const fmtTime = (t?: number) =>
  t ? new Date(t).toLocaleString('en-IN', { day: '2-digit', month: 'short', hour: '2-digit', minute: '2-digit', hour12: false }) : '—';
export const fmtClock = (t: number) => new Date(t).toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit', hour12: false });

/** Colour + shape + text for every road status (never colour alone). */
export const STATUS_STYLE: Record<SegmentStatus, { color: string; glyph: string; dash?: string }> = {
  VERIFIED_PASSABLE: { color: 'var(--color-ok)', glyph: '●' },
  POTENTIAL_HAZARD: { color: 'var(--color-warn)', glyph: '▲', dash: '10 5' },
  BLOCKED: { color: 'var(--color-crit)', glyph: '■' },
  UNKNOWN: { color: 'var(--color-unk)', glyph: '○', dash: '2 6' },
  STALE_EVIDENCE: { color: 'var(--color-stale)', glyph: '◌', dash: '6 6' },
  CONFLICTING_EVIDENCE: { color: 'var(--color-conf)', glyph: '◆', dash: '14 4 2 4' },
};

export function StatusChip({ status, compact }: { status: SegmentStatus; compact?: boolean }) {
  const st = STATUS_STYLE[status];
  return (
    <span
      className="inline-flex items-center gap-1.5 whitespace-nowrap rounded-[2px] px-1.5 py-[1px] text-[12px] font-medium"
      style={{ color: st.color, background: `color-mix(in srgb, ${st.color} 12%, transparent)` }}
    >
      <span aria-hidden className="text-[9px]">{st.glyph}</span>
      {compact ? STATUS_LABEL[status].split(' ')[0] : STATUS_LABEL[status]}
    </span>
  );
}

export function Tag({ children, tone = 'neutral', title }: { children: ReactNode; tone?: 'neutral' | 'ok' | 'warn' | 'crit' | 'accent' | 'sim'; title?: string }) {
  const c = { neutral: 'var(--color-muted)', ok: 'var(--color-ok)', warn: 'var(--color-warn)', crit: 'var(--color-crit)', accent: 'var(--color-accent)', sim: 'var(--color-stale)' }[tone];
  return (
    <span title={title} className="inline-flex items-center whitespace-nowrap rounded-[2px] px-1.5 py-[1px] text-[12px] font-medium" style={{ color: c, background: `color-mix(in srgb, ${c} 11%, transparent)` }}>
      {children}
    </span>
  );
}

export const SimTag = () => <Tag tone="sim" title="Generated by the built-in simulation, not field data">SIMULATED</Tag>;

export function ConfidenceTag({ c }: { c: Confidence }) {
  return <Tag tone={c === 'High' ? 'ok' : c === 'Medium' ? 'warn' : 'neutral'}>{c} confidence</Tag>;
}

export function PriorityTag({ p }: { p: Priority }) {
  return <Tag tone={p === 'P1' ? 'crit' : p === 'P2' ? 'warn' : 'neutral'}>{p}</Tag>;
}

export const Mono = ({ children, className }: { children: ReactNode; className?: string }) => <span className={cx('font-mono text-[12.5px]', className)}>{children}</span>;

type BtnProps = ButtonHTMLAttributes<HTMLButtonElement> & { variant?: 'primary' | 'secondary' | 'ghost' | 'danger'; size?: 'sm' | 'md'; icon?: ReactNode };
export function Button({ variant = 'secondary', size = 'md', icon, className, children, ...rest }: BtnProps) {
  return (
    <button
      {...rest}
      className={cx(
        'inline-flex items-center justify-center gap-1.5 rounded-[3px] border font-medium transition-colors disabled:cursor-not-allowed disabled:opacity-40',
        size === 'sm' ? 'h-7 px-2.5 text-[12.5px]' : 'h-9 px-3.5 text-[13.5px]',
        variant === 'primary' && 'border-ink bg-ink text-bg hover:opacity-90',
        variant === 'secondary' && 'border-line-strong bg-surface-2 text-ink hover:bg-raised',
        variant === 'ghost' && 'border-transparent text-muted hover:bg-surface-2 hover:text-ink',
        variant === 'danger' && 'border-crit/60 text-crit hover:bg-crit/10',
        className,
      )}
    >
      {icon}
      {children}
    </button>
  );
}

